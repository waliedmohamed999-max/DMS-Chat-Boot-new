import type { Prisma } from "@prisma/client";

/**
 * محرك ردود مُبرمَج بالكامل (بلا أي استدعاء LLM) لوضع العرض التجريبي المجاني — مطابقة كلمات مفتاحية
 * بسيطة على نص الزائر، مع استثناءين اثنين فقط يقرآن قاعدة البيانات الحقيقية (قراءة مجانية، لا تكلفة
 * OpenAI): الأسعار من جدول Plan، ومدة التجربة المجانية من PlatformSettings — حتى لا يعرض العرض
 * التجريبي أرقاماً وهمية لعميل محتمل فعلي يشاهده. بقية الردود نصوص عربية ثابتة مختصرة (مناسبة للنطق
 * الصوتي أيضاً عبر speechSynthesis في ChatWidget.tsx).
 */
export async function getDemoReply(tx: Prisma.TransactionClient, text: string): Promise<string> {
  const normalized = text.trim();

  // "أسعار"/"باقات" (جمع التكسير) لا تحتوي "سعر"/"باقة" (المفرد) كنص فرعي حرفياً بسبب إدراج الألف في
  // صيغة الجمع (سعر → أسعار، باقة → باقات) — اكتُشف هذا فعلياً أثناء اختبار حي (عبارة "الأسعار" وحدها
  // كانت تسقط للرد الافتراضي العام بدل فرع السعر الحقيقي)، فأُضيفت الصيغتان صراحة بدل الاعتماد على
  // المفرد فقط.
  if (/سعر|أسعار|باقة|باقات|تكلفة|اشتراك/.test(normalized)) {
    const plans = await tx.plan.findMany({
      where: { isActive: true, isCustomForTenantId: null },
      orderBy: { priceMonthlySar: "asc" },
      select: { name: true, priceMonthlySar: true },
    });
    if (plans.length === 0) return "عندنا باقات متعددة تناسب كل حجم متجر — تواصل معنا لتفاصيل الأسعار الحالية.";
    const list = plans.map((p) => `${p.name} بـ${p.priceMonthlySar} ريال شهرياً`).join("، ");
    return `أسعارنا الحالية: ${list}. تحب تعرف تفاصيل أكتر عن أي باقة؟`;
  }

  if (/ذكاء اصطناعي|موظف ذكي|بوت ذكي|الموظف الذكي/.test(normalized)) {
    return "الموظف الذكي عندنا يرد على عملائك تلقائياً على واتساب، يفهم استفساراتهم، ويحوّلهم لموظف بشري لما الموضوع يحتاج تدخّل حقيقي. متاح من باقة النمو فما فوق.";
  }

  if (/واتساب|ربط رقم|whatsapp/i.test(normalized)) {
    return "بتقدر تربط رقم واتساب حقيقي عبر WhatsApp Business Platform الرسمي، أو تجرّب المنصة أول بربط تجريبي بمسح QR بلا أي إعداد معقّد.";
  }

  if (/تجربة|تجارب|مجاني/.test(normalized)) {
    const settings = await tx.platformSettings.findUniqueOrThrow({ where: { id: "singleton" } });
    return `عندنا تجربة مجانية ${settings.defaultTrialDays} يوم، بلا أي بطاقة ائتمان مطلوبة للبدء.`;
  }

  // "متاجر" (جمع تكسير لـ"متجر") نفس فئة خلل جمع "أسعار" أعلاه — مُضافة صراحة لنفس السبب.
  if (/زد|سلة|تكامل|متجر|متاجر/.test(normalized)) {
    return "بنربط مباشرة مع منصتي زد وسلة — طلباتك ومنتجاتك تتزامن تلقائياً، وتقدر تستهدف عملاء السلات المتروكة برسالة استرداد آلية.";
  }

  return "سؤال رائع! هذا عرض تجريبي مبسّط — لو حابب تجربة كاملة لمنصتنا، فريقنا جاهز يوريك كل التفاصيل الفعلية.";
}
